#!/usr/bin/env python3
"""Tables for S25b-recal (results/reflex/s25_memory_need/recal): writes recal_tables.md and recal_summary.json.
Recovered = back within 95 % of the pre-drop result, measured as 95 % of the pre-drop gain over a no-learning
baseline (share on target over 0; flakes lost under the open-loop valve, 8.6, for the furnace and under the GP
planner alone for the stop; flagging: false alarms <= 7.5 % and AUROC gain over 0.5 >= 95 % of the pre-drop gain).
Paired two-sided Wilcoxon tests against the pre-drop result (seeds 1-20).
Usage: python analyze_recal.py RESULTS_DIR (results/reflex/s25_memory_need)
"""
import json, sys
import numpy as np
from scipy.stats import wilcoxon

R = sys.argv[1]; J = {j: json.load(open(f"{R}/recal/s25r_{j}.json"))["per_seed"] for j in ("flag", "stop", "furnace", "dose")}
SD = [str(s) for s in range(1, 21)]
pw = lambda a, b: 1.0 if np.allclose(a, b) else float(wilcoxon(a, b).pvalue)  # noqa: E731
fp = lambda p: "-" if p is None else (f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}")  # noqa: E731
L, OUT = ["# S25b-recal tables (generated by analyze_recal.py)", ""], {}

# dose
NS = [5, 10, 20, 41, 82, 123]; D = J["dose"]
L += ["## Dose: share on target after the drop, recalibrated only on new-intensity spectra", "",
      "| arm | before drop | no recalibration | " + " | ".join(f"recal {n}" for n in NS) + " | spectra to 95 % of before | p (recal 123 vs before) |",
      "|---|---|---|" + "---|" * (len(NS) + 2)]
OUT["dose"] = {}
for a in ("G_lookup", "P_lookup", "E_ridge", "knn"):
    m = lambda t: float(np.mean([D[s][f"{a}|{t}"]["success"] for s in SD]))  # noqa: E731
    b = m("before"); v = [m(f"recal{n}") for n in NS]; need = next((n for n, x in zip(NS, v) if x >= 0.95 * b), None)
    p = pw([D[s][f"{a}|recal123"]["success"] for s in SD], [D[s][f"{a}|before"]["success"] for s in SD])
    fit = float(np.mean([D[s][f"fit_seconds|recal123"].get(a, np.nan) for s in SD])) if a in ("E_ridge", "G_lookup") else None
    OUT["dose"][a] = dict(before=b, norecal=m("norecal"), recal=dict(zip(NS, v)), n_to_95=need, p_recal123_vs_before=p, fit_seconds_123=fit,
                          mae_before=float(np.mean([D[s][f"{a}|before"]["mae"] for s in SD])), mae_recal123=float(np.mean([D[s][f"{a}|recal123"]["mae"] for s in SD])))
    L.append(f"| {a} | {b:.3f} | {m('norecal'):.3f} | " + " | ".join(f"{x:.3f}" for x in v) + f" | {need if need else '> 123'} | {fp(p)} |")
L.append("")

# furnace
NS = [10, 20, 45, 90, 180, 360, 540]; F = J["furnace"]
L += ["## Furnace end point: flakes lost after the drop, recalibrated only on new-intensity readings", "",
      "| arm | before drop | no recalibration | " + " | ".join(f"recal {n}" for n in NS) + " | readings to 95 % of before | p (recal 540 vs before) |",
      "|---|---|---|" + "---|" * (len(NS) + 2)]
OUT["furnace"] = {}
for a in ("G_kc", "E_bands"):
    m = lambda t: float(np.mean([F[s][f"{a}|{t}"] for s in SD]))  # noqa: E731
    b = m("before"); v = [m(f"recal{n}") for n in NS]; tgt = 8.6 - 0.95 * (8.6 - b)
    need = next((n for n, x in zip(NS, v) if x <= tgt), None)
    p = pw([F[s][f"{a}|recal540"] for s in SD], [F[s][f"{a}|before"] for s in SD])
    fit = float(np.mean([F[s][f"fit_seconds|{a}|recal540"] for s in SD]))
    OUT["furnace"][a] = dict(before=b, norecal=m("norecal"), recal=dict(zip(NS, v)), n_to_95=need, p_recal540_vs_before=p, fit_seconds_540=fit)
    L.append(f"| {a} | {b:.2f} | {m('norecal'):.2f} | " + " | ".join(f"{x:.2f}" for x in v) + f" | {need if need else '> 540'} | {fp(p)} |")
L.append("")

# stop
CS = ["recal3", "recal6", "recal10", "recal_all"]; S = J["stop"]; gp = float(np.mean([S[s]["gp_alone"]["lost"] for s in SD]))
L += ["## Failing-run stop: flakes lost of 30, drop from probe 15; memory cleared at the drop, then learned from the first C post-drop runs", "",
      f"GP planner alone: {gp:.2f}.", "",
      "| arm | no drop | drop, memory kept | " + " | ".join(c.replace("recal", "recal C ") for c in CS) + " | runs to 95 % of no-drop | p (kept vs no drop) / (recal all vs no drop) |",
      "|---|---|---|" + "---|" * (len(CS) + 2)]
OUT["stop"] = {}
for a in ("G_fly", "P_fly_best", "E_logreg_C10", "knn"):
    m = lambda t: float(np.mean([S[s][f"{a}|{t}"]["lost"] for s in SD]))  # noqa: E731
    v = {c: m(c) for c in ["nodrop", "kept"] + CS}; tgt = gp - 0.95 * (gp - v["nodrop"])
    need = next((c[5:] for c in CS if v[c] <= tgt), None)
    p1 = pw([S[s][f"{a}|kept"]["lost"] for s in SD], [S[s][f"{a}|nodrop"]["lost"] for s in SD])
    p2 = pw([S[s][f"{a}|recal_all"]["lost"] for s in SD], [S[s][f"{a}|nodrop"]["lost"] for s in SD])
    OUT["stop"][a] = dict(v, runs_to_95=need, p_kept=p1, p_recal_all=p2)
    L.append(f"| {a} | {v['nodrop']:.2f} | {v['kept']:.2f} | " + " | ".join(f"{v[c]:.2f}" for c in CS) + f" | {need if need else 'not within 15'} | {fp(p1)} / {fp(p2)} |")
L.append("")

# flag
OFFS = [0, 5, 10, 20, 41, 82, 180, 400, 1000]; G = J["flag"]
L += ["## Flagging (S1b, drop at reading 2,000): false alarms / recall / AUROC in 400-reading windows starting n readings after the drop", "",
      "Threshold fixed at its pre-drop value. recal = memory reset at the drop then online; norecal = online throughout. Means over 20 seeds.", "",
      "| arm | pre-drop | " + " | ".join(f"n {o}" for o in OFFS) + " | readings to recover |", "|---|---|" + "---|" * (len(OFFS) + 1)]
OUT["flag"] = {}
for a in ("G_fly_ctx", "P_fly_ctx25", "E_zscore_fam", "E_knnfam"):
    for c in ("norecal", "recal"):
        k = f"{a}|{c}"
        mm = lambda w, q: float(np.nanmean([np.nan if G[s][k][w][q] is None else G[s][k][w][q] for s in SD]))  # noqa: E731
        pre = {q: mm("pre", q) for q in ("fa", "recall", "auroc")}
        cells, rec = [], None
        for o in OFFS:
            fa, rc, au = mm(f"n{o}", "fa"), mm(f"n{o}", "recall"), mm(f"n{o}", "auroc")
            cells.append(f"{fa:.2f} / {rc:.2f} / {au:.3f}")
            if rec is None and fa <= 0.075 and au - 0.5 >= 0.95 * (pre["auroc"] - 0.5): rec = o
        OUT["flag"][k] = dict(pre=pre, windows={o: {q: mm(f"n{o}", q) for q in ("fa", "recall", "auroc")} for o in OFFS}, readings_to_recover=rec)
        L.append(f"| {a}, {c} | {pre['fa']:.2f} / {pre['recall']:.2f} / {pre['auroc']:.3f} | " + " | ".join(cells) + f" | {rec if rec is not None else '> 1,000'} |")
L.append("")
open(f"{R}/recal_tables.md", "w").write("\n".join(L) + "\n")
json.dump(OUT, open(f"{R}/recal_summary.json", "w"), indent=1, default=str)
print("\n".join(L))

#!/usr/bin/env python3
"""Tables for S25 (results/reflex/s25_memory_need): writes tables.md and summary.json.
Paired two-sided Wilcoxon signed-rank tests; Holm correction within each job (all frozen-vs-online tests of that job).
"Reaches 95 %" = 95 % of the gain over a no-learning baseline: AUROC over 0.5, share on target over 0, flakes lost
under the no-stop baseline (failing-run stop: GP planner alone, per seed; furnace: open-loop valve, 8.6 flakes, paper).
Usage: python analyze_s25.py RESULTS_REFLEX_DIR
"""
import glob, json, os, sys
import numpy as np
from scipy.stats import wilcoxon
from s5_long import auroc

RR = sys.argv[1]; R = f"{RR}/s25_memory_need"
OPEN_LOOP_FURNACE = 8.6


def pw(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    return 1.0 if np.allclose(a, b) else float(wilcoxon(a, b).pvalue)


def holm(ps):
    ps = np.asarray(ps, float); o = np.argsort(ps); m = len(ps); adj = np.empty(m); run = 0.0
    for r, i in enumerate(o): run = max(run, min(1.0, (m - r) * ps[i])); adj[i] = run
    return adj


def fp(p): return "-" if p is None else (f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}")


def load(mode):
    return {j["seed"]: j for j in (json.load(open(f)) for f in glob.glob(f"{R}/a/s25a_{mode}_s*.json"))}


L = ["# S25 tables (generated by analyze_s25.py)", ""]; SUM = {}

# ============================================================ A. flagging
METH = ["fly", "fly_rec", "fly_ctx2", "zscore", "zscore_fam", "knn_n92", "knn_n184", "knnfam_n184", "ae16"]
CONDS = ["frozen", "reset100", "reset1000", "online"]
streams = {m: load(m) for m in ("s1b", "long", "shift")}
tests = []
for mode, D in streams.items():
    for m in METH:
        if not D: continue
        sd = sorted(D); f = [D[s]["det"][f"{m}|frozen"]["auroc"] for s in sd]; o = [D[s]["det"][f"{m}|online"]["auroc"] for s in sd]
        tests.append((mode, m, pw(f, o)))
adj = dict(zip([(a, b) for a, b, _ in tests], holm([p for *_, p in tests]))) if tests else {}
L += ["## A. Does each job need memory?", "", "### Job i, flagging: AUROC median over seeds by memory condition", "",
      "Frozen = learns during the first 300 readings only. Holm-corrected p (frozen vs online) over all "
      f"{len(tests)} flagging tests.", ""]
SUM["A_flag"] = {}
for mode, D in streams.items():
    if not D: continue
    sd = sorted(D)
    L += [f"**{mode}** ({len(sd)} seeds)", "", "| method | frozen | reset 100 | reset 1,000 | online | frozen − online, seeds frozen higher | Holm p |", "|---|---|---|---|---|---|---|"]
    SUM["A_flag"][mode] = {}
    for m in METH:
        v = {c: np.array([D[s]["det"][f"{m}|{c}"]["auroc"] for s in sd]) for c in CONDS}
        d = v["frozen"] - v["online"]
        SUM["A_flag"][mode][m] = dict({c: float(np.median(x)) for c, x in v.items()}, diff=float(np.median(d)), p_holm=float(adj[(mode, m)]))
        L.append(f"| {m} | " + " | ".join(f"{np.median(v[c]):.3f}" for c in CONDS) + f" | {np.median(d):+.3f}, {(d > 0).sum()}/{len(sd)} | {fp(adj[(mode, m)])} |")
    L.append("")

D = streams["shift"]
if D:
    sd = sorted(D)
    keys = ["auroc", "alarm_accepted", "alarm_rare_first", "alarm_rare_ret_1e3", "alarm_rare_ret_1e4", "alarm_rare_ret_6e4",
            "alarm_routine_early", "alarm_routine_late", "recall_new_late"]
    L += ["### Shifting stream: what each condition alarms on (medians over 10 seeds)", "",
          "Threshold: 95th percentile of routine scores in readings 300-5,000 (so routine early is about 0.05 by construction). "
          "Accepted MoTe2 should not alarm; genuinely new should; the rare phase is new at first sight. Routine late = after 2.6-3 cm-1 of drift.", "",
          "| method, condition | AUROC new | accepted MoTe2 | rare 1st | rare +1e3 | rare +1e4 | rare +6e4 | routine early | routine late | recall new late |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    SUM["A_shift"] = {}
    for m in METH:
        for c in ("frozen", "reset1000", "online"):
            row = {k: float(np.median([D[s]["det"][f"{m}|{c}"][k] for s in sd])) for k in keys}; SUM["A_shift"][f"{m}|{c}"] = row
            L.append(f"| {m}, {c} | " + " | ".join(f"{row[k]:.3f}" if k == "auroc" else f"{row[k]:.2f}" for k in keys) + " |")
    L.append("")

D = streams["s1b"]
if D:
    sd = sorted(D)
    L += ["### Laser drop (S1b, reading 2,000): readings until false alarms return to the pre-drop level", "",
          "Threshold = 95th percentile of the 300 normal readings before the drop; recovered = first block of 100 normal readings "
          "after the drop with at most 7.5 % alarms. Median readings over seeds that recover; never = no block recovers in the 2,000 readings after the drop.", "",
          "| method | frozen | reset 1,000 | online | online: first block alarm share |", "|---|---|---|---|---|"]
    SUM["A_drop"] = {}
    for m in METH:
        cells = []
        for c in ("frozen", "reset1000", "online"):
            r = [D[s]["det"][f"{m}|{c}"]["readings_to_recover"] for s in sd]; ok = [x for x in r if x is not None]
            cells.append(f"{int(np.median(ok)) if ok else '-'} ({len(sd) - len(ok)} never)"); SUM["A_drop"][f"{m}|{c}"] = dict(median=float(np.median(ok)) if ok else None, never=len(sd) - len(ok))
        fb = np.median([D[s]["det"][f"{m}|online"]["fa_blocks_after_drop"][0] for s in sd])
        L.append(f"| {m} | " + " | ".join(cells) + f" | {fb:.2f} |")
    L.append("")

D = load("stop")
if D:
    sd = sorted(D); SC = ["frozen3", "frozen6", "frozen10", "frozen15", "reset10", "online"]
    MS = ["fly", "fly_best", "logreg_C1", "logreg_C10", "knn", "mlp"]
    gp = np.array([D[s]["det"]["gp_alone"]["lost"] for s in sd])
    ps = [(m, c, pw([D[s]["det"][f"{m}|{c}"]["lost"] for s in sd], [D[s]["det"][f"{m}|online"]["lost"] for s in sd])) for m in MS for c in ("frozen3", "frozen10")]
    ad = dict(zip([(m, c) for m, c, _ in ps], holm([p for *_, p in ps])))
    L += ["### Job ii, failing-run stop: flakes lost of 30 (mean of 20 seeds) by memory condition", "",
          f"Frozen C = learns from the first C completed runs only; reset 10 = memory cleared every 10 completed runs (one campaign has 30 probes, "
          f"so resets every 100 or 1,000 readings equal online). GP planner alone: {gp.mean():.2f}. Holm over {len(ps)} tests.", "",
          "| method | " + " | ".join(SC) + " | Holm p frozen 3 / frozen 10 vs online | runs to 95 % of benefit |", "|---|" + "---|" * (len(SC) + 2)]
    SUM["A_stop"] = {}
    for m in MS:
        mu = {c: float(np.mean([D[s]["det"][f"{m}|{c}"]["lost"] for s in sd])) for c in SC}
        tgt = gp.mean() - 0.95 * (gp.mean() - mu["online"]); need = next((int(c[6:]) for c in SC[:4] if mu[c] <= tgt), ">15")
        SUM["A_stop"][m] = dict(mu, p_frozen3=float(ad[(m, "frozen3")]), p_frozen10=float(ad[(m, "frozen10")]), runs_to_95=need)
        L.append(f"| {m} | " + " | ".join(f"{mu[c]:.2f}" for c in SC) + f" | {fp(ad[(m, 'frozen3')])} / {fp(ad[(m, 'frozen10')])} | {need} |")
    L += ["", "Jobs iii (dose) and iv (furnace end point) learn only from their calibration flakes and receive no labelled data afterwards: "
          "frozen by construction in the paper's harnesses, so frozen = online trivially; their calibration-size curves are in part B.", ""]

# ============================================================ B. generic vs specialists
L += ["## B. One generic model or specialists at the edge station", ""]
B = {j: json.load(open(f"{R}/b/s25b_{j}.json"))["per_seed"] for j in ("dose", "furnace", "family", "stopdrop", "flagspec") if os.path.exists(f"{R}/b/s25b_{j}.json")}
TIM = json.load(open(f"{R}/timing.json")) if os.path.exists(f"{R}/timing.json") else None
S24 = json.load(open(f"{RR}/s24_fixed_memory/summary.json"))["s24b"]
mean = lambda j, arm, key=None: float(np.mean([(B[j][s][arm][key] if key else B[j][s][arm]) for s in B[j]]))  # noqa: E731

if TIM and "dose" in B and "flagspec" in B:
    fs = {k: mean("flagspec", "P_ctx25", k) for k in ("new_phase", "wrong_sample")}
    i24 = S24["i"]; ii = S24["ii"]
    rows = [("flag new phase / wrong sample (AUROC)", f"{i24['module_ctx']['new_phase']:.3f} / {i24['module_ctx']['wrong_sample']:.3f}",
             f"{fs['new_phase']:.3f} / {fs['wrong_sample']:.3f}", f"{i24['zscore_fam']['new_phase']:.3f} / {i24['zscore_fam']['wrong_sample']:.3f}"),
            ("stop a failing run (flakes lost)", f"{ii['fly']['lost']:.2f}", f"{ii['fly_best']['lost']:.2f}", f"{ii['logreg_C10']['lost']:.2f} (C 10); {ii['logreg_C1']['lost']:.2f} (C 1)"),
            ("dose (share on target; error)", f"{mean('dose', 'G_lookup|n123', 'success'):.3f}; {100 * mean('dose', 'G_lookup|n123', 'mae'):.1f} %",
             f"{mean('dose', 'P_lookup|n123', 'success'):.3f}; {100 * mean('dose', 'P_lookup|n123', 'mae'):.1f} %",
             f"{mean('dose', 'E_ridge|n123', 'success'):.3f}; {100 * mean('dose', 'E_ridge|n123', 'mae'):.1f} %"),
            ("furnace end point (flakes lost)", f"{mean('furnace', 'GP_kc|n540'):.2f}", f"{mean('furnace', 'GP_kc|n540'):.2f}", f"{mean('furnace', 'E_bands|n540'):.2f}")]
    F = TIM["fit"]
    L += ["### Accuracy, bytes and time per station (test seeds 1-20)", "",
          "G = one generic connectome model at its defaults; P = one tuned connectome model per job sharing the measured wiring "
          "(flag 2.5 % with context, stop with gain control, dose 10 %, furnace 5 % code); E = engineered specialists.", "",
          "| | G generic | P per-job connectome | E engineered |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
    L += [f"| packed bytes | {F['G']['packed_total'] / 1e3:.1f} kB | {F['P']['packed_total'] / 1e3:.1f} kB (four separate wirings: {F['P4']['packed_total'] / 1e3:.0f} kB) | {F['E']['packed_total'] / 1e3:.1f} kB |",
          f"| µs per spectrum, all four jobs (one Grace core) | {TIM['G_us_per_spectrum']:.0f} | {TIM['P_us_per_spectrum']:.0f} | {TIM['E_us_per_spectrum_s24']:.1f} (S24) |", ""]
    SUM["B_station"] = dict(rows=rows, fit=F, timing={k: v for k, v in TIM.items() if k.endswith("spectrum") or k.endswith("s24")})

L += ["### Setup cost: settings tuned and labelled examples to reach 95 % of the paper result", "",
      "Settings: what each option tunes to reach its reported number (grids of S23). Examples: from the curves below.", ""]
setup = [("flag", "G: none (defaults; context gain fixed at 2)", "P: sparsity x context gain (9)", "E: none (z-score); routing needs the sample log, as G and P"),
         ("stop", "G: none", "P: sparsity x gain control (9)", "E: C (5) for logistic regression"),
         ("dose", "G: none", "P: sparsity x gain control (9)", "E: ridge lambda (5)"),
         ("furnace", "G: ridge lambda on the code (5)", "P: ridge lambda on the code (5)", "E: ridge lambda (5)")]
L += ["| job | G generic | P per-job connectome | E engineered |", "|---|---|---|---|"] + [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in setup]
L += ["", "Total settings tuned: G 1 (5 candidates), P 4 jobs x 2 settings + 1 (41 candidates), E 3 (15 candidates).", ""]


def reach(ns, vals, final, base, higher=True):
    tgt = base + 0.95 * (final - base)
    for n, v in zip(ns, vals):
        if (v >= tgt) if higher else (v <= tgt): return n
    return None


if "dose" in B:
    NS = [5, 10, 20, 41, 82, 123]; arms = ["G_lookup", "P_lookup", "E_ridge", "knn"]
    L += ["### Adding (or setting up) the dose job: share on target by labelled calibration spectra", "",
          "G/P: a new read-out (lookup) on the existing Kenyon-cell code; E: a new ridge on the bands. 41 = one flake, 123 = the paper's three.", "",
          "| arm | " + " | ".join(f"n {n}" for n in NS) + " | n to 95 % | p vs E at n 123 |", "|---|" + "---|" * (len(NS) + 2)]
    SUM["B_dose"] = {}
    e123 = [B["dose"][s]["E_ridge|n123"]["success"] for s in B["dose"]]
    for a in arms:
        v = [mean("dose", f"{a}|n{n}", "success") for n in NS]; nr = reach(NS, v, v[-1], 0.0)
        p = pw([B["dose"][s][f"{a}|n123"]["success"] for s in B["dose"]], e123) if a != "E_ridge" else None
        SUM["B_dose"][a] = dict(curve=dict(zip(NS, v)), n_to_95=nr, p_vs_E=p)
        L.append(f"| {a} | " + " | ".join(f"{x:.3f}" for x in v) + f" | {nr} | {fp(p)} |")
    L.append("")
if "furnace" in B:
    NS = [10, 20, 45, 90, 180, 360, 540]
    L += ["### Adding (or setting up) the furnace end point: flakes lost of 30 by labelled readings", "",
          "G/P: a new ridge read-out on the Kenyon-cell code (lambda 0.1); E: a new ridge on the bands (lambda 1e-2). 180 = one flake.", "",
          "| arm | " + " | ".join(f"n {n}" for n in NS) + " | n to 95 % |", "|---|" + "---|" * (len(NS) + 1)]
    SUM["B_furnace"] = {}
    for a in ("GP_kc", "E_bands"):
        v = [mean("furnace", f"{a}|n{n}") for n in NS]; nr = reach(NS, v, v[-1], OPEN_LOOP_FURNACE, higher=False)
        SUM["B_furnace"][a] = dict(curve=dict(zip(NS, v)), n_to_95=nr)
        L.append(f"| {a} | " + " | ".join(f"{x:.2f}" for x in v) + f" | {nr} |")
    L.append("")
if "family" in B:
    BINS = [0, 10, 20, 40, 80, 160, 320, 640, 1280]
    arms = list(B["family"]["1"][0][2])
    L += ["### Adding a material family to the flagger: AUROC on the new family by its readings seen (pooled over 20 seeds)", "",
          "G: generic model with a new context quarter; P: the same at 2.5 %; E: a new routed z-score or a new 46-spectrum reservoir.", "",
          "| arm | " + " | ".join(f"{a}-{b}" for a, b in zip(BINS[:-1], BINS[1:])) + " | readings to 95 % |", "|---|" + "---|" * len(BINS)]
    SUM["B_family"] = {}
    rows_all = [r for s in B["family"] for r in B["family"][s]]
    for a in arms:
        v = []
        for lo, hi in zip(BINS[:-1], BINS[1:]):
            sel = [r for r in rows_all if lo <= r[0] < hi]; pos = [r[2][a] for r in sel if r[1]]; neg = [r[2][a] for r in sel if not r[1]]
            v.append(float(auroc(np.array(pos), np.array(neg))) if pos and neg else float("nan"))
        nr = reach(BINS[:-1], v, v[-1], 0.5)
        SUM["B_family"][a] = dict(curve=dict(zip(BINS[:-1], v)), readings_to_95=nr)
        L.append(f"| {a} | " + " | ".join(f"{x:.3f}" for x in v) + f" | {nr} |")
    L.append("")

L += ["### Instrument change (laser power to 1/3): which deployed models need recalibrating, and with how many examples", ""]
SUM["B_drop"] = {}
if "stopdrop" in B:
    L += ["Failing-run stop (drop from probe 15 of 30): flakes lost.", "", "| arm | no drop | drop, memory kept | drop, memory cleared | p drop vs no drop |", "|---|---|---|---|---|"]
    for a in ("G_fly", "P_fly_best", "E_logreg_C10", "knn"):
        v = {c: [B["stopdrop"][s][f"{a}|{c}"]["lost"] for s in B["stopdrop"]] for c in ("nodrop", "drop", "drop_reset")}
        p = pw(v["drop"], v["nodrop"]); SUM["B_drop"][f"stop|{a}"] = dict({c: float(np.mean(x)) for c, x in v.items()}, p=p)
        L.append(f"| {a} | {np.mean(v['nodrop']):.2f} | {np.mean(v['drop']):.2f} | {np.mean(v['drop_reset']):.2f} | {fp(p)} |")
    L.append("")
if "dose" in B:
    NN = [0, 5, 10, 20, 41]
    L += ["Dose (calibrated before the drop, used after it): share on target by spectra of one new calibration flake at the new intensity.", "",
          "| arm | before drop | " + " | ".join(f"+{n}" for n in NN) + " | p (+0 vs before) |", "|---|---|" + "---|" * (len(NN) + 1)]
    for a in ("G_lookup", "P_lookup", "E_ridge", "knn"):
        b0 = [B["dose"][s][f"{a}|n123"]["success"] for s in B["dose"]]; d0 = [B["dose"][s][f"{a}|drop_new0"]["success"] for s in B["dose"]]
        v = [mean("dose", f"{a}|drop_new{n}", "success") for n in NN]; p = pw(d0, b0)
        SUM["B_drop"][f"dose|{a}"] = dict(before=float(np.mean(b0)), after=dict(zip(NN, v)), p=p)
        L.append(f"| {a} | {np.mean(b0):.3f} | " + " | ".join(f"{x:.3f}" for x in v) + f" | {fp(p)} |")
    L.append("")
if "furnace" in B:
    NN = [0, 10, 45, 180]
    L += ["Furnace end point: flakes lost by readings of one new calibration flake at the new intensity.", "",
          "| arm | before drop | " + " | ".join(f"+{n}" for n in NN) + " | p (+0 vs before) |", "|---|---|" + "---|" * (len(NN) + 1)]
    for a in ("GP_kc", "E_bands"):
        b0 = [B["furnace"][s][f"{a}|n540"] for s in B["furnace"]]; d0 = [B["furnace"][s][f"{a}|drop_new0"] for s in B["furnace"]]
        v = [mean("furnace", f"{a}|drop_new{n}") for n in NN]; p = pw(d0, b0)
        SUM["B_drop"][f"furnace|{a}"] = dict(before=float(np.mean(b0)), after=dict(zip(NN, v)), p=p)
        L.append(f"| {a} | {np.mean(b0):.2f} | " + " | ".join(f"{x:.2f}" for x in v) + f" | {fp(p)} |")
    L.append("")

if TIM:
    F = TIM["fit"]
    L += ["### Fit on a Raspberry Pi Pico (264 kB SRAM, 2 MB flash) and Pico 2 (520 kB SRAM, 4 MB flash)", "",
          "All in RAM = packed bytes + working arrays (one drive per code family); with flash = read-only parts (wiring, stored codes, "
          "regression weights) in flash, RAM holds only what is written at run time.", "",
          "| option | packed | all in RAM | Pico | Pico 2 | RAM with flash | Pico | Pico 2 |", "|---|---|---|---|---|---|---|---|"]
    yn = lambda b: "yes" if b else "no"  # noqa: E731
    for o, lbl in (("G", "G generic"), ("P", "P per-job, shared wiring"), ("P4", "P per-job, four wirings"), ("E", "E engineered")):
        f = F[o]
        L.append(f"| {lbl} | {f['packed_total'] / 1e3:.1f} kB | {f['all_in_ram'] / 1e3:.1f} kB | {yn(f['pico_ram'])} | {yn(f['pico2_ram'])} | "
                 f"{f['ram_with_flash'] / 1e3:.1f} kB | {yn(f['pico_flash'])} | {yn(f['pico2_flash'])} |")
    sub = TIM["generic_job_subsets"]
    fitp = [k for k, v in sub.items() if v["pico"]]
    L += ["", f"Generic model, all in RAM on a Pico: fits with {', '.join(fitp) if fitp else 'no job set'}; "
          f"all four jobs need {sub['flag+stop+dose+furnace']['all_in_ram'] / 1e3:.1f} kB.", ""]
    SUM["B_fit"] = dict(fit=F, subsets=sub)

open(f"{R}/tables.md", "w").write("\n".join(L) + "\n")
json.dump(SUM, open(f"{R}/summary.json", "w"), indent=1, default=str)
print("\n".join(L))
